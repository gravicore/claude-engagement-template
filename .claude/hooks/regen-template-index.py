#!/usr/bin/env python3
"""Regenerate index.md from the frontmatter of all *.md files in a templates/ directory.

Two ways to call it:
  python3 regen-template-index.py <templates_dir>   explicit directory
  python3 regen-template-index.py                    PostToolUse hook: reads the hook JSON on stdin and
                                                     acts only when tool_input.file_path is a markdown
                                                     file sitting directly in a templates/ directory
"""
import json
import sys
import os
import re


def parse_frontmatter(content):
    m = re.match(r"^---\n(.*?)\n---", content, re.DOTALL)
    if not m:
        return {}
    fm = m.group(1)

    result = {}

    name = re.search(r"^name:\s*(.+)$", fm, re.MULTILINE)
    if name:
        result["name"] = name.group(1).strip()

    desc = re.search(r"^description:\s*(.+)$", fm, re.MULTILINE)
    if desc:
        result["description"] = desc.group(1).strip()

    version = re.search(r"^version:\s*(.+)$", fm, re.MULTILINE)
    if version:
        result["version"] = version.group(1).strip()

    triggers_block = re.search(r"^triggers:\n((?:[ \t]+-[ \t]+.+\n?)+)", fm, re.MULTILINE)
    if triggers_block:
        result["triggers"] = [
            re.sub(r"^[ \t]*-[ \t]+", "", line).strip()
            for line in triggers_block.group(1).splitlines()
            if line.strip()
        ]
    else:
        result["triggers"] = []

    return result


def dir_from_hook_input():
    """Return the templates directory named by the hook JSON on stdin, or None when not applicable."""
    try:
        payload = json.load(sys.stdin)
    except ValueError:
        return None
    path = (payload.get("tool_input") or {}).get("file_path") or ""
    if not re.search(r"(^|/)templates/[^/]+\.md$", path) or os.path.basename(path) == "index.md":
        return None
    return os.path.dirname(path)


def main():
    if len(sys.argv) >= 2:
        templates_dir = sys.argv[1]
    else:
        templates_dir = dir_from_hook_input()
        if templates_dir is None:
            sys.exit(0)

    if not os.path.isdir(templates_dir):
        print(f"Not a directory: {templates_dir}", file=sys.stderr)
        sys.exit(1)

    entries = []
    for fname in sorted(os.listdir(templates_dir)):
        if not fname.endswith(".md") or fname == "index.md":
            continue
        path = os.path.join(templates_dir, fname)
        with open(path) as f:
            content = f.read()
        fm = parse_frontmatter(content)
        if not fm.get("name"):
            print(f"[template-index] Skipping {fname} - no frontmatter name", file=sys.stderr)
            continue
        entries.append({**fm, "file": fname})

    lines = [
        "<!-- AUTO-GENERATED by .claude/hooks/regen-template-index.py - do not edit manually -->",
        "<!-- Regenerated whenever a templates/*.md file is written (PostToolUse hook) -->",
        "",
        "# Available Templates",
        "",
        "| name | file | triggers | description |",
        "|------|------|----------|-------------|",
    ]
    for e in entries:
        triggers_str = ", ".join(f"`{t}`" for t in e.get("triggers", []))
        lines.append(
            f"| `{e['name']}` | `{e['file']}` | {triggers_str} | {e.get('description', '')} |"
        )
    lines.append("")

    index_path = os.path.join(templates_dir, "index.md")
    if not entries and not os.path.exists(index_path):
        sys.exit(0)
    with open(index_path, "w") as f:
        f.write("\n".join(lines))

    print(f"[template-index] Regenerated {index_path} ({len(entries)} template(s))")


if __name__ == "__main__":
    main()
